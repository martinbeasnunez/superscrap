function detectBrowserLocale(): Locale {
  if (typeof window === 'undefined') return 'es';

  // Check localStorage first
  const saved = localStorage.getItem('orbit_locale');
  if (saved === 'en' || saved === 'es') return saved;

  // Detect from browser
  const browserLang = navigator.language || (navigator as { userLanguage?: string }).userLanguage || 'es';
  return browserLang.startsWith('en') ? 'en' : 'es';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('es');
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    setLocaleState(detectBrowserLocale());
    setMounted(true);
  }, []);

  const setLocale = useCallback((newLocale: Locale) => {
    setLocaleState(newLocale);
    localStorage.setItem('orbit_locale', newLocale);
  }, []);

  const t = useCallback((key: string): string => {
    return translations[locale]?.[key] || translations['es']?.[key] || key;
  }, [locale]);

  const value = useMemo(() => ({
    locale: mounted ? locale : 'es' as Locale,
    setLocale,
    t: mounted ? t : (key: string) => translations['es']?.[key] || key,
  }), [mounted, locale, setLocale, t]);

  return (
    <I18nContext.Provider value={value}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

// Language selector for landing pages (white on dark bg)
export function LanguageSelector({ className = '' }: { className?: string }) {
  const { locale, setLocale } = useI18n();

  return (
    <div className={`flex items-center gap-1 ${className}`}>
      <button
        onClick={() => setLocale('es')}
        className={`px-2 py-1 rounded text-sm font-medium transition-all ${
          locale === 'es'
            ? 'bg-white/20 text-white'
            : 'text-white/60 hover:text-white/80'
        }`}
      >
        ES
      </button>
      <span className="text-white/40">|</span>
      <button
        onClick={() => setLocale('en')}
        className={`px-2 py-1 rounded text-sm font-medium transition-all ${
          locale === 'en'
            ? 'bg-white/20 text-white'
            : 'text-white/60 hover:text-white/80'
        }`}
      >
        EN
      </button>
    </div>
  );
}

